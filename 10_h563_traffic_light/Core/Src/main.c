int __io_putchar(int ch)
{
    HAL_UART_Transmit(&huart3, (uint8_t *)&ch, 1, HAL_MAX_DELAY);   // USART3 on this board!
    return ch;
}

void setLights(LightState s)
{
    HAL_GPIO_WritePin(LED_GREEN_GPIO_Port,  LED_GREEN_Pin,  s == GREEN  ? GPIO_PIN_SET : GPIO_PIN_RESET);
    HAL_GPIO_WritePin(LED_YELLOW_GPIO_Port, LED_YELLOW_Pin, s == YELLOW ? GPIO_PIN_SET : GPIO_PIN_RESET);
    HAL_GPIO_WritePin(LED_RED_GPIO_Port,    LED_RED_Pin,    s == RED    ? GPIO_PIN_SET : GPIO_PIN_RESET);
}

void goTo(LightState next, const char *why)
{
    printf("[%lu ms] %s -> %s (%s)\r\n", HAL_GetTick(), names[state], names[next], why);
    state = next;
    stateStart = HAL_GetTick();
    setLights(state);
}

void HAL_GPIO_EXTI_Rising_Callback(uint16_t GPIO_Pin)   // H5 uses Rising/Falling callbacks
{
    if (GPIO_Pin == BUTTON_Pin && state == GREEN)
    {
        walkRequest = 1;
    }
}
